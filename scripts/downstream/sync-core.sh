#!/usr/bin/env bash
# Copies a QuantMeridian-Core build into a checkout of the downstream repository and commits it to the
# sync branch. Does not talk to GitHub beyond `git push` (the workflow opens and merges the PR).
#
#   sync-core.sh <built-dir> <downstream-checkout> <source-sha> [branch]
#
# Prints `changed=true|false` (also appended to $GITHUB_OUTPUT when set). Idempotent: an identical
# build produces no commit and no push.
set -euo pipefail

BUILT="${1:?built dir}"; TARGET="${2:?downstream checkout}"; SHA="${3:?source sha}"; BRANCH="${4:-sync/upstream}"

rsync -a --delete --exclude '.git' --exclude 'node_modules' --exclude 'dist*' "$BUILT"/ "$TARGET"/
cd "$TARGET"
git add -A
if git diff --cached --quiet; then
  echo "changed=false"; [ -n "${GITHUB_OUTPUT:-}" ] && echo "changed=false" >> "$GITHUB_OUTPUT"
  exit 0
fi

git checkout -q -B "$BRANCH"
git -c user.name="quantmeridian-core-sync" -c user.email="sync@users.noreply.github.com" \
  commit -q -m "Sync from QuantMeridian ${SHA:0:7}" -m "Generated by the QuantMeridian-Core sync. Do not edit by hand."
git push -q --force origin "$BRANCH"
echo "changed=true"; [ -n "${GITHUB_OUTPUT:-}" ] && echo "changed=true" >> "$GITHUB_OUTPUT"
