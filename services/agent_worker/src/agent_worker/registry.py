"""Metric registry loader (spec009 REQ-009, T-004).

Reads ``contracts/agent/generated/metric_registry.json`` (generated by
``npm run export:agent-metric-registry``), checks its schema and its content hash, and builds
the QuantSmith ``0008`` ``SemanticLayer`` from it. Loading needs no QuantSmith; building the
layer imports ``quantsmith.pipelines.metrics_semantic_layer`` lazily, from whichever copy the
worker's sourcing step has put on the path.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from importlib import import_module
from pathlib import Path
from typing import Any

from .contracts import contracts_dir, validate_contract

SEMANTIC_LAYER_MODULE = "quantsmith.pipelines.metrics_semantic_layer"


class RegistryError(Exception):
    """The registry file is unreadable, incompatible, or does not match its recorded hash."""


class UnknownMetricError(KeyError):
    """A plan named a metric outside the registry (rejected before execution, AC-009)."""


def canonical_json(value: Any) -> str:
    """Stable JSON identical to ``canonicalJson`` in src/lib/server/agent/metricRegistry.ts."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def registry_version(body: dict[str, Any]) -> str:
    """``sha256:`` of the canonical JSON of the registry without its ``registry_version``."""
    payload = {k: v for k, v in body.items() if k != "registry_version"}
    return "sha256:" + hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip().lower())


@dataclass(frozen=True)
class Registry:
    version: str
    metrics: dict[str, dict[str, Any]]
    desk_datasets: dict[str, dict[str, Any]]
    excluded: dict[str, str]
    _synonyms: dict[str, str]

    def metric(self, name: str) -> dict[str, Any]:
        try:
            return self.metrics[name]
        except KeyError:
            raise UnknownMetricError(name) from None

    def resolve(self, text: str) -> str | None:
        """The metric a name or synonym refers to, or None. Synonyms are unique by construction."""
        key = _normalize(text)
        if key in self._synonyms:
            return self._synonyms[key]
        return next((n for n in self.metrics if _normalize(n) == key), None)

    def names(self, data_class: str | None = None) -> list[str]:
        return sorted(
            n
            for n, m in self.metrics.items()
            if data_class is None or m["data_class"] == data_class
        )


def load_registry(path: Path | None = None) -> Registry:
    path = path or (contracts_dir() / "generated" / "metric_registry.json")
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise RegistryError(f"cannot read metric registry {path}: {error}") from error

    verdict = validate_contract("registry", doc)
    if not verdict.ok:
        detail = "; ".join(f"{i.path}: {i.message}" for i in verdict.issues[:5])
        raise RegistryError(f"metric registry is not a valid registry document: {detail}")
    if registry_version(doc) != doc["registry_version"]:
        raise RegistryError("metric registry content does not match its registry_version")

    metrics = {m["name"]: m for m in doc["metrics"]}
    synonyms: dict[str, str] = {}
    for name, metric in metrics.items():
        for syn in metric["synonyms"]:
            key = _normalize(syn)
            if synonyms.get(key, name) != name:
                raise RegistryError(f'synonym "{key}" is claimed by {synonyms[key]} and {name}')
            synonyms[key] = name
    return Registry(
        version=doc["registry_version"],
        metrics=metrics,
        desk_datasets={d["id"]: d for d in doc["desk_datasets"]},
        excluded={e["name"]: e["reason"] for e in doc["excluded"]},
        _synonyms=synonyms,
    )


# --- desk measures -----------------------------------------------------------------------------


def _expr_value(expr: dict[str, Any], row: dict[str, Any]) -> float:
    """Per-row value of a desk expression: sum over terms of the product of the term's fields."""
    total = 0.0
    for term in expr["terms"]:
        product = 1.0
        for field in term:
            product *= float(row[field])
        total += product
    return total


def desk_measures(metric: dict[str, Any], row: dict[str, Any]) -> dict[str, float]:
    """The fact measures one desk row contributes for ``metric`` (names match the layer)."""
    measure = metric["source"]["measure"]
    if "numerator" in measure:
        return {
            f"{metric['name']}__num": _expr_value(measure["numerator"], row),
            f"{metric['name']}__den": _expr_value(measure["denominator"], row),
        }
    return {metric["name"]: _expr_value(measure, row)}


def build_semantic_layer(registry: Registry, semantic_module: Any | None = None) -> Any:
    """Register every registry metric in a QuantSmith ``0008`` ``SemanticLayer``.

    Gold series are measure metrics over a fact measure named after the series. Desk measures
    use one fact measure per metric; desk ratios use ``<name>__num`` / ``<name>__den``, which
    the layer divides over the same filtered rows (0008 REQ-003).
    """
    module = semantic_module or import_module(SEMANTIC_LAYER_MODULE)
    layer = module.SemanticLayer()
    for name in sorted(registry.metrics):
        metric = registry.metrics[name]
        dimensions = tuple(metric["dimensions"])
        common = {"name": name, "owner": metric["owner"], "grain": metric["grain"]}
        source = metric["source"]
        if source["kind"] == "desk_dataset" and "numerator" in source["measure"]:
            for side in ("numerator", "denominator"):
                if source["measure"][side]["fn"] != "sum":
                    raise RegistryError(
                        f"{name}: ratio {side} must be a sum (0008 sums both sides)"
                    )
            layer.define(
                **common,
                dimensions=dimensions,
                numerator=f"{name}__num",
                denominator=f"{name}__den",
            )
        else:
            agg = source["measure"]["fn"] if source["kind"] == "desk_dataset" else metric["agg"]
            if agg not in ("sum", "count", "mean"):
                raise RegistryError(f"{name}: aggregation {agg!r} is not supported by 0008")
            layer.define(**common, dimensions=dimensions, source=name, agg=agg)
    return layer
